import assert from "node:assert/strict";
import {SceneDocument,applyOperations} from "./scene.mjs";
import {parseIntent,executeIntent} from "./intent.mjs";

let doc=new SceneDocument();
let result=executeIntent("创建一个红色立方体",doc);
doc=result.document;
assert.equal(doc.entities.length,1);
assert.equal(doc.entities[0].color,"#d65c55");
const id=doc.entities[0].id;
result=executeIntent("把红色立方体改成白色",doc);
doc=result.document;
assert.equal(doc.get(id).color,"#e8e9e4");
result=executeIntent("把最后一个物体移动到左边",doc);
doc=result.document;
assert.equal(doc.get(id).position[0],-2);
result=executeIntent("把最后一个物体放大一倍",doc);
doc=result.document;
assert.equal(doc.get(id).scale[0],2);
result=executeIntent("删除最后一个物体",doc);
doc=result.document;
assert.equal(doc.entities.length,0);
result=executeIntent("在桌面上放一座蓝色城堡",doc);
doc=result.document;
assert.equal(doc.entities.length,10);
assert.ok(doc.entities.every(e=>e.color==="#5b91d1" || e.name==="城堡大门"));
result=executeIntent("把城堡改成白色",doc);doc=result.document;
assert.ok(doc.entities.every(e=>e.color==="#e8e9e4"));
const castleX=doc.entities.map(e=>e.position[0]);
result=executeIntent("把城堡移动到左边",doc);doc=result.document;
assert.deepEqual(doc.entities.map(e=>e.position[0]),castleX.map(x=>x-2));
const snap=doc.snapshot();
assert.equal(SceneDocument.restore(snap).snapshot(),snap);
assert.throws(()=>applyOperations(doc,[{op:"delete",id:doc.entities[0].id},{op:"update",id:"missing",patch:{name:"x"}}]));
assert.equal(doc.entities.length,10);
assert.throws(()=>doc.create({type:"dragon"}));
assert.throws(()=>doc.update(doc.entities[0].id,{color:"red"}));
console.log("PASS: natural-language command planning, atomic operations, CRUD and snapshot restore");
